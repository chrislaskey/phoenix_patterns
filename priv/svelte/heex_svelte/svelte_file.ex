defmodule HeexSvelte.SvelteFile do
  @moduledoc """
  Writes a component's `.svelte` file and reads back the header that keeps
  it in step with the component.

  The header records two hashes:

    * `source`, of the component's template and its attr and slot
      declarations when the file was last written or accepted. When it no
      longer matches the component, the file is stale
    * `output`, of what the generator wrote below the header. When the file
      no longer matches it, someone edited it by hand, and the generator
      leaves it alone. A file written by hand from the start has `none`
  """

  alias HeexSvelte.{Expr, Source, Template}

  @marker "heex-svelte:"
  @header ~r/\A<!--\n(?<text>.*?)\n  heex-svelte: source=(?<source>\w+) output=(?<output>\w+)\n-->\n/s

  @doc "The `.svelte` path for a component: its PascalCase name, next to its source file."
  def path(%Source{file: file, function: function}) do
    Path.join(Path.dirname(file), svelte_name(function) <> ".svelte")
  end

  @doc "The PascalCase name a component's Svelte file and tag use."
  def svelte_name(function), do: Macro.camelize(to_string(function))

  @doc """
  A hash of everything the file depends on: the template, or the whole
  component for one written by hand, and the attr and slot declarations,
  without their docs and line numbers.
  """
  def source_hash(%Source{template: template, code: code, spec: spec}) do
    declarations = %{
      attrs: spec.attrs |> Enum.map(&declaration/1) |> Enum.sort(),
      slots: spec.slots |> Enum.map(&declaration/1) |> Enum.sort()
    }

    # A hand-written file follows the whole component, since there is no
    # template to follow
    hash(:erlang.term_to_binary({template || code, declarations}, [:deterministic]))
  end

  defp declaration(declaration) do
    declaration
    |> Map.drop([:line, :doc])
    |> Map.update(:opts, [], &Keyword.delete(&1, :doc))
    |> Map.update(:attrs, [], fn attrs -> attrs |> Enum.map(&declaration/1) |> Enum.sort() end)
  end

  defp hash(binary), do: :crypto.hash(:sha256, binary) |> Base.encode16(case: :lower) |> binary_part(0, 12)

  @doc """
  Reads the file at `path` into `{:ok, %{source:, output:, body:}}`,
  `{:error, :no_header}` or `{:error, :enoent}`. `:edited?` is true when the
  body differs from what the generator last wrote.
  """
  def read(path) do
    with {:ok, contents} <- File.read(path) do
      case Regex.named_captures(@header, contents) do
        %{"source" => source, "output" => output} ->
          body = Regex.replace(@header, contents, "")
          {:ok, %{source: source, output: output, body: body, edited?: hash(body) != output}}

        nil ->
          {:error, :no_header}
      end
    end
  end

  @doc "True when `contents` starts with a heex-svelte header."
  def generated?(contents), do: Regex.match?(@header, contents)

  @doc """
  Renders the whole file for `component`. `resolve` turns a component call
  in the template into `{:ok, name, %Source{}}` or `:error`.

  Returns `{:ok, contents}` or `{:error, line, message}`.
  """
  def render(%Source{} = component, resolve) do
    attrs = Enum.map(component.spec.attrs, & &1.name)
    slots = Enum.map(component.spec.slots, & &1.name)
    resolve = fn type, name -> resolve.(component, type, name) end

    ctx = %{attrs: attrs, slots: slots, first_line: component.first_line, resolve: resolve}
    {markup, uses} = Template.translate(component.template, ctx)
    body = script(component, uses) <> "\n" <> String.trim_trailing(markup) <> "\n"
    {:ok, header(component, source_hash(component), hash(body)) <> body}
  catch
    {:heex_svelte, line, message} -> {:error, line || component.line, message}
  end

  @doc "Restamps the file at `path` with `component`'s current source hash, keeping its body."
  def accept(path, %Source{} = component) do
    {output, body} =
      case read(path) do
        {:ok, %{output: output, body: body}} -> {output, body}
        {:error, :no_header} -> {"none", File.read!(path)}
      end

    File.write!(path, header(component, source_hash(component), output) <> body)
  end

  defp header(component, source, "none") do
    """
    <!--
      Written by hand to mirror #{inspect(component.module)}.#{component.function}/1
      in #{component.file}. After changing the component, update this
      file to match and run `mix app.svelte --accept #{path(component)}`.
      #{@marker} source=#{source} output=none
    -->
    """
  end

  defp header(component, source, output) do
    """
    <!--
      Generated by `mix app.svelte` from #{inspect(component.module)}.#{component.function}/1
      in #{component.file}. After changing the component, run
      `mix app.svelte` again, or edit this file by hand to match and run
      `mix app.svelte --accept #{path(component)}`.
      #{@marker} source=#{source} output=#{output}
    -->
    """
  end

  defp script(component, uses) do
    imports =
      for {:component, name, target} <- uses do
        relative = Path.relative_to(path(target), Path.dirname(path(component)), force: true)
        relative = if String.starts_with?(relative, "."), do: relative, else: "./" <> relative
        ~s(  import #{name} from "#{relative}"\n)
      end

    emit? = :emit in uses

    props =
      if component.spec.attrs == [] and component.spec.slots == [] do
        []
      else
        [props_type(component.spec, uses), "  let { ", props(component.spec), " } = $props()\n"]
      end

    lines = [
      if(emit?, do: ~s(  import { getContext } from "svelte"\n), else: ""),
      imports,
      if((emit? or imports != []) and props != [], do: "\n", else: ""),
      props,
      if(emit?, do: emit(), else: "")
    ]

    "<script>\n" <> IO.iodata_to_binary(lines) <> "</script>\n"
  end

  defp emit do
    """

      // Calls the app's event handler, see `setContext("app:emit", ...)`
      const emit = getContext("app:emit") ?? ((name) => console.warn(`no app:emit handler for ${name}`))
    """
  end

  defp props(spec) do
    {globals, attrs} = Enum.split_with(spec.attrs, &(&1.type == :global))

    attrs =
      Enum.map(attrs, fn attr ->
        js = Expr.js_name(attr.name)
        binding = if js == to_string(attr.name), do: js, else: "#{attr.name}: #{js}"

        case Keyword.fetch(attr.opts, :default) do
          {:ok, default} -> "#{binding} = #{Expr.literal(default)}"
          :error -> binding
        end
      end)

    slots = Enum.map(spec.slots, &Expr.slot_js_name(&1.name))
    rest = Enum.map(globals, &("..." <> Expr.js_name(&1.name)))

    Enum.join(attrs ++ slots ++ rest, ", ")
  end

  defp props_type(spec, uses) do
    {globals, attrs} = Enum.split_with(spec.attrs, &(&1.type == :global))

    properties =
      Enum.map(attrs, fn attr ->
        optional? = not attr.required or Keyword.has_key?(attr.opts, :default)
        name = if optional?, do: "[#{attr.name}]", else: to_string(attr.name)
        "   * @property {#{type(attr)}} #{name}\n"
      end) ++
        Enum.map(spec.slots, fn slot ->
          name = Expr.slot_js_name(slot.name)
          name = if slot.required, do: name, else: "[#{name}]"
          "   * @property {import(\"svelte\").Snippet<#{snippet_arguments(slot.name, uses)}>} #{name}\n"
        end)

    rest = if globals == [], do: "", else: " & Record<string, any>"

    "  /**\n   * @typedef {Object} Props\n#{properties}   */\n\n  /** @type {Props#{rest}} */\n"
  end

  # Svelte's Snippet type takes a tuple of arguments; an array type makes it `never`.
  defp snippet_arguments(slot, uses) do
    case Enum.uniq(for {:render_slot, ^slot, arity} <- uses, do: arity) |> Enum.sort() do
      [1] -> "[any]"
      [0, 1] -> "[any?]"
      _ -> "[]"
    end
  end

  defp type(%{opts: opts} = attr) do
    case Keyword.get(opts, :values) do
      values when is_list(values) -> Enum.map_join(values, " | ", &Expr.literal/1)
      _ -> base_type(attr.type)
    end
  end

  defp base_type(type) when type in [:string, :atom], do: "string"
  defp base_type(:boolean), do: "boolean"
  defp base_type(type) when type in [:integer, :float], do: "number"
  defp base_type(:list), do: "any[]"
  defp base_type(:map), do: "Record<string, any>"
  defp base_type(_type), do: "any"
end
